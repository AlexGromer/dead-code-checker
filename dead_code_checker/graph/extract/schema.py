"""graph.extract.schema: the schema languages SQL, protobuf and GraphQL files.
Queries are DATA (data/queries/<grammar>/{defs,refs}.scm), the rules are data/xlang.json "schema", this module only maps matches to Facts, a
function of (lang, text) only. A grammar that is not installed is ExtractorMissing (cfg.parse), never a fallback. The names are "<tag>:<name>" with
the name escaped like in the config languages (model.qual_name), the objects are classes (a table, a view, a message, a type ...) or funcs (a
function, a procedure, an rpc, a field of a root type), so the verdicts and the confirmation rule (graph.verdict) read them like any symbol.
  sql       defs  table:<name>, view:<name> (a materialized view too), function:<name>, procedure:<name>; a schema-qualified name keeps its
                  schema (`table:public%2Eorders`). Refs (kind schema, name `sql:<name>`): the tables a statement names, read from the text of
                  the statement by graph.extract.xlang.sql_names (FROM / JOIN / INTO / UPDATE, REFERENCES, ALTER TABLE, TRUNCATE, GRANT, CALL,
                  EXECUTE FUNCTION ...; the names of a WITH are no tables), from the definition the statement creates (a view reads its tables,
                  a function body its tables, a table its foreign keys) or, for any other statement (an ALTER, an INSERT of a data script), from
                  the file: the objects a migration alters are used by the file, and the file is a soft root when its tool runs it
                  (data frameworks.json schema_run_files: graph.roots). A name built at run time is a glob (`sql:audit_*`).
  proto     defs  message:<pkg.Name> (a nested message is <pkg.Outer.Inner>), enum:<..>, service:<pkg.Name>, rpc:<pkg.Service.Method>. Refs: every type
                  a field, a map or an rpc names, from the message or the rpc that holds it; a service reaches its rpcs and a message the types
                  declared inside it (a nested type lives with its owner). The generated code (FooGrpc, foo_pb2 ...) reaches them from code
                  (graph.xlink code_edges).
  graphql   defs  type:<Name>, interface:<Name>, input:<Name>, enum:<Name>, union:<Name> and field:<Type.field> for the fields of the root operation
                  types (Query, Mutation, Subscription: data schema.graphql.roots, and the types a `schema { query: X }` block names, which carry the
                  ref `=query`, the operation they are the root of: the resolvers write `Query.<field>` and graph.xlink reads it as a field of X): their
                  resolvers are the entry points of the API, so only a field with a resolver is used (graph.xlink, frameworks.json schema rules).
                  Refs: every named type, from the type or the root field that writes it; `Book implements Node` is the ref `~Node` (an interface
                  also reaches its implementers: graph.xlink). A root type is a soft root (the clients call it); the types that no live field,
                  member or interface reaches are the ones that are dead.
Generated files (generated.json "headers" in the first KB: `Generated by the protocol buffer compiler`, `@generated`) flag every definition
generated: the objects stay in the graph, nobody is told that one is unused; the vendored copies of a schema file by path (google/protobuf,
vendored/, third-party/) are left out of the graph by graph.link.path_flags from generated.json "paths" (only schema files: code of other languages stays). The mapping reads text and nodes only; nothing is executed.
Cost: the scope of a ref (the definition that holds it) is one sweep over the definitions (_Nest) and a bisect per ref, the scope of a SQL
statement a bisect over the starts, so a schema dump of any size (the reader takes files up to MAX_FILE_BYTES) costs n log n, never a scan per
object (tests/test_graph_schema.py bounds the CPU time of a 1 MB dump per language).
"""

from __future__ import annotations

import hashlib
import os
from bisect import bisect_left, bisect_right
from typing import Dict, List, NamedTuple, Optional, Tuple

from ..contracts import Extractor, register_extractor
from ..model import F_GENERATED, Facts, Finding, RootHint, qual_name
from . import cfg, xlang as xl
from .common import generated_head, generated_sha
from .ts_generic import probe_grammar

KINDS = {  # tag -> (node kind, visibility)
    "table": ("class", "package"),
    "view": ("class", "package"),
    "function": ("func", "package"),
    "procedure": ("func", "package"),
    "message": ("class", "public"),
    "enum": ("class", "public"),
    "service": ("class", "public"),
    "rpc": ("func", "public"),
    "type": ("class", "public"),
    "interface": ("class", "public"),
    "input": ("class", "public"),
    "union": ("class", "public"),
    "field": ("func", "public"),
}


class _Item(NamedTuple):
    tag: str
    name: str  # as written, dotted
    node: object  # the definition node: start_byte, end_byte, start_point, end_point


class _Src:
    """A parse with the helpers every mapping needs."""

    def __init__(self, text: str, data: bytes, parsed):
        self.text, self.data, self.parsed, self.out = text, data, parsed, cfg._Out()

    def txt(self, n) -> str:
        return self.data[n.start_byte : n.end_byte].decode("utf-8", "replace")

    @staticmethod
    def line(n) -> int:
        return n.start_point[0] + 1

    def items(self, prefixes: Tuple[str, ...] = ("def.",)) -> List[_Item]:
        """The definitions of defs.scm, sorted by (start, -end): one per definition node, the name that starts first."""
        found: Dict[Tuple[int, int, str], Tuple[int, str, object]] = {}
        for _, caps in self.parsed.run("defs"):
            names = sorted(caps.get("name", ()), key=lambda n: n.start_byte)
            for key, nodes in caps.items():
                if not key.startswith(prefixes) or not names:
                    continue
                for n in nodes:
                    k = (n.start_byte, n.end_byte, key[4:] if key.startswith("def.") else key)
                    if k not in found or names[0].start_byte < found[k][0]:
                        found[k] = (names[0].start_byte, self.txt(names[0]), n)
        return [
            _Item(k[2], v[1], v[2]) for k, v in sorted(found.items(), key=lambda kv: (kv[0][0], -kv[0][1], kv[0][2]))
        ]

    def define(self, tag: str, name: str, node) -> str:
        kind, vis = KINDS[tag]
        return self.out.d(f"{tag}:{qual_name(name)}", kind, self.line(node), node.end_point[0] + 1, vis)

    def ref(self, group: str, name: str, node, scope: str) -> None:
        self.out.r(f"{group}:{name}", "schema", self.line(node), scope)


class _Nest:
    """The innermost of nested `(start, end, qual)` spans at a byte position ('' = none): one sweep with a stack over the spans, sorted here by
    (start, -end) (the stable sort keeps the later one of two equal spans innermost), then a bisect per query, so a schema dump of any size
    costs n log n, never n per reference."""

    def __init__(self, spans: List[Tuple[int, int, str]]):
        self.cuts: List[int] = []  # the positions where the innermost span changes
        self.quals: List[str] = []  # the innermost span from the cut with the same index on
        stack: List[Tuple[int, str]] = []  # (end, qual) of the open spans, the innermost last

        def cut(pos: int) -> None:
            qual = stack[-1][1] if stack else ""
            if self.cuts and self.cuts[-1] == pos:
                self.quals[-1] = qual
            else:
                self.cuts.append(pos)
                self.quals.append(qual)

        for start, end, qual in sorted(spans, key=lambda sp: (sp[0], -sp[1])):
            while stack and stack[-1][0] <= start:
                cut(stack.pop()[0])
            stack.append((end, qual))
            cut(start)
        while stack:
            cut(stack.pop()[0])

    def at(self, pos: int) -> str:
        i = bisect_right(self.cuts, pos) - 1
        return self.quals[i] if i >= 0 else ""


# ================================================================== sql
def _sql(s: _Src) -> None:
    spans, mine = [], {}  # the definitions as (start, end, qual); qual -> the name it defines, folded
    for it in s.items():
        own = xl.sql_clean(it.name)
        qual = s.define(it.tag, own, it.node)
        spans.append((it.node.start_byte, it.node.end_byte, qual))
        mine[qual] = own.lower()
    starts, end = [sp[0] for sp in spans], -1
    for n in sorted(
        (n for _, caps in s.parsed.run("refs") for n in caps.get("stmt", ())), key=lambda n: (n.start_byte, -n.end_byte)
    ):
        if n.start_byte < end:
            continue  # inside a statement that was read whole (a procedure body, a CTE)
        end = n.end_byte
        scope, i = "", bisect_left(
            starts, n.start_byte
        )  # the first definition that lies inside the statement (spans are sorted by start)
        while i < len(spans) and spans[i][0] < end:
            if spans[i][1] <= end:
                scope = spans[i][2]
                break
            i += 1
        for name in xl.sql_names(s.txt(n), ddl=True):
            if name.lower() != mine.get(scope):
                s.ref("sql", name, n, scope)


# ================================================================== proto
def _proto(s: _Src) -> None:
    pkg: List[str] = []
    for _, caps in s.parsed.run("defs"):
        for n in caps.get("pkg", ()):
            pkg = s.txt(n).strip().strip(".").split(".")
    stack, spans = [], []  # stack: (end byte, name segments, qual) of the enclosing definitions
    for it in s.items():
        while stack and stack[-1][0] <= it.node.start_byte:
            stack.pop()
        segs = (stack[-1][1] if stack else pkg) + [it.name]
        qual = s.define(it.tag, ".".join(segs), it.node)
        spans.append((it.node.start_byte, it.node.end_byte, qual))
        if stack:  # a nested type lives with its owner, an rpc with its service
            s.ref("proto", ".".join(segs), it.node, stack[-1][2])
        stack.append((it.node.end_byte, segs, qual))
    inner = _Nest(spans)
    for _, caps in s.parsed.run("refs"):
        for n in caps.get("ref", ()):
            s.ref("proto", s.txt(n).strip().strip("."), n, inner.at(n.start_byte))


# ================================================================== graphql
def _graphql(s: _Src) -> None:
    d = xl.data()["schema"]["graphql"]
    roots, builtin, ops = set(d["roots"]), set(d["builtin"]), {}
    for _, caps in s.parsed.run(
        "defs"
    ):  # `schema { query: RootQuery }`: RootQuery is a root, and the type of the operation `query`
        ops.update((s.txt(n), s.txt(o).strip().lower()) for n, o in zip(caps.get("root", ()), caps.get("op", ())))
    roots |= set(ops)
    items = s.items(("def.", "ext.", "field"))
    holders = _Nest([(it.node.start_byte, it.node.end_byte, it.name) for it in items if it.tag in ("type", "ext.type")])
    spans = []  # the definitions and the root fields: the scope of a ref
    for it in items:
        n = it.node
        if it.tag == "ext.type":  # `extend type X` defines nothing
            continue
        if it.tag == "field":
            owner = holders.at(n.start_byte)
            if owner not in roots:
                continue  # the field of any other type is part of the type
            qual = s.define("field", f"{owner}.{it.name}", n)
        else:
            qual = s.define(it.tag, it.name, n)
            if it.tag == "type" and it.name in roots:  # the clients call a root operation type
                s.out.roots.append(RootHint("init", qual, s.line(n), "soft", "convention"))
                if (
                    it.name in ops
                ):  # its fields are `Query.<field>` too for the resolvers (graph.xlink: `graphql:=query` names the operation)
                    s.ref("graphql", "=" + ops[it.name], n, qual)
        spans.append((n.start_byte, n.end_byte, qual))
    impls = _Nest(
        [(n.start_byte, n.end_byte, "~") for _, caps in s.parsed.run("refs") for n in caps.get("impls", ())]
    )  # the implements clauses (nested for `A & B`): a named type inside one is an interface
    inner = _Nest(spans)
    for _, caps in s.parsed.run("refs"):
        for n in caps.get("ref", ()):
            if s.txt(n) not in builtin:
                s.ref("graphql", impls.at(n.start_byte) + s.txt(n), n, inner.at(n.start_byte))


# ================================================================== extractor
class Schema(Extractor):
    name, version, langs = "schema", 1, ("sql", "proto", "graphql")

    def grammar_sha(self, lang: str) -> str:
        # the mapping code, the helpers it calls (cfg._Out), the xlang rules (sql_names) and the generated markers decide the facts as well
        base = cfg.grammar_sha(lang, os.path.abspath(__file__), cfg.__file__)
        return hashlib.sha256(f"{base}|{xl.sha()}|{generated_sha()}".encode()).hexdigest()

    def probe(self, lang: str, cfg: Optional[dict] = None) -> Optional[Finding]:
        return probe_grammar(lang, cfg)

    def extract(self, lang: str, path: str, text: str) -> Facts:
        text = text[1:] if text[:1] == "﻿" else text
        data = text.encode("utf-8", "replace")
        s = _Src(text, data, cfg.parse(lang, data))
        {"sql": _sql, "proto": _proto, "graphql": _graphql}[lang](s)
        if generated_head(text):  # written by a generator: the objects are nobody's to remove
            s.out.defs = [d._replace(flags=d.flags | F_GENERATED) for d in s.out.defs]
        return s.out.facts(lang, text, int(s.parsed.errors))


register_extractor(Schema())
