def symbols(lang: str, text: str) -> List[XSym]:
    """Top-level declarations of one extra-language file. Same contract as core.generic_symbols plus public and
    decorated flags. start/end are 1-based; body is the text between the braces of a function (groups A) or None."""
    if lang not in EXTRA_LANGS:
        return []
    lines = text.split("\n")
    offsets, pos = [], 0
    for ln in lines:
        offsets.append(pos)
        pos += len(ln) + 1
    out: List[XSym] = []
    if lang == "css":
        return _css_symbols(lines)
    indent = 0
    if lang in ("cs", "php") and _CS_NS_BLOCK.search(text):
        indent = 8
    skip = _SKIP_NAMES.get(lang, set())
    seen_lines = set()
    budget = Budget(BRACE_TOKENS_PER_CHAR * len(_TOKEN.findall(text)) + BRACE_TOKENS_MIN)
    hs_memo: Dict[str, Tuple[int, int]] = {}
    ends = _end_lines(lines) if lang in ("rb", "lua", "ex") else None

    def brace_block(idx: int, kind: str):
        nxt = offsets[idx + 1] if idx + 1 < len(lines) else len(text)
        brace = text.find("{", offsets[idx], nxt + 401)  # a brace further away is "none"
        seg = text[offsets[idx] : brace] if brace >= 0 else ""
        arrow = "=>" in lines[idx] and re.search(r"=>\s*$", seg) is None
        if (
            brace < 0
            or arrow
            or (";" in seg and "(" not in seg)
            or re.search(r";\s*$", seg.split("\n")[0].rstrip())
        ):
            return None, idx + 1
        close = brace_end(text, brace, budget=budget)
        if close < 0:
            return None, idx + 1
        return (text[brace + 1 : close - 1] if kind == "function" else None), bisect.bisect_right(offsets, close)

    if lang == "c":
        for idx, name, _b in _c_static_fns(lines, text, offsets):
            body, end = brace_block(idx, "function")
            out.append(XSym("function", name, idx + 1, end, body, False, False))
            seen_lines.add(idx)
        for idx, ln in enumerate(lines):
            if idx in seen_lines:
                continue
            m = _C_STRUCT.match(ln)
            if m:
                _b, end = brace_block(idx, "class")
                out.append(XSym("class", m.group("n"), idx + 1, end, None, True, False))
                continue
            m = _C_DEFINE.match(ln)
            if m and not _C_GUARD.search(m.group("n")) and not m.group("n").startswith("__"):
                out.append(XSym("constant", m.group("n"), idx + 1, idx + 1, None, False, False))
        out.sort(key=lambda s: s.start)
        return out
    rules = _rules_for(lang, indent)
    for idx, ln in enumerate(lines):
        hit = None
        for kind, rx in rules:
            m = rx.match(ln)
            if m:
                hit = (kind, m)
                break
        if hit is None and lang == "dart" and ln[:1] not in (" ", "\t", "}", "/", "@", ")", "#") and ln.strip():
            m = None
            if len(ln) <= MAX_SIG_LINE and "(" in ln and (ln.rstrip().endswith("{") or "=>" in ln):
                m = _DART_FN.match(ln)
            if (
                m
                and m.group("n") not in _DART_KW
                and ln.split("(")[0].split()[0] not in _DART_KW
                and (ln.rstrip().endswith("{") or "=>" in ln)
            ):
                hit = ("function", m)
        if hit is None:
            continue
        kind, m = hit
        name = m.group("n")
        gd = m.groupdict()
        mods = gd.get("mods") or ""
        if lang == "lua":
            mods = "local" if gd.get("loc") else ""
            name = re.split(r"[.:]", name)[-1]
        if lang in ("rb", "ex"):
            name = re.split(r"::|\.", name)[-1]
        if name in skip:
            continue
        if lang == "hs" and kind == "function" and name in ("main",):
            continue
        decorated = lang in ("java", "cs", "kt", "scala", "swift", "dart", "php") and _annotations(
            lines, idx, lang, gd.get("ann") or ""
        )
        if lang == "scala" and kind == "class" and re.search(r"extends\s+(App|IOApp)\b", ln):
            continue
        body, end = None, idx + 1
        if lang in _BRACE_LANGS:
            body, end = brace_block(idx, kind if kind != "constant" else "constant")
            if kind == "constant":
                body = None
                end = idx + 1
        elif lang in ("rb", "lua", "ex"):
            end = _end_keyword(lines, idx, ends) if kind != "constant" else idx + 1
        elif lang == "hs":
            end = _hs_end(lines, idx, name, hs_memo) if kind == "function" else _hs_end_type(lines, idx)
        elif lang == "r":
            nxt = offsets[idx + 1] if idx + 1 < len(lines) else len(text)
            brace = text.find("{", offsets[idx], nxt + 200)
            if brace >= 0:
                close = brace_end(text, brace, hash_comment=True, budget=budget)
                if close > 0:
                    end = bisect.bisect_right(offsets, close)
        pub = _public(lang, kind, name, mods, lines, idx)
        out.append(XSym(kind, name, idx + 1, max(end, idx + 1), body, pub, decorated))
    return out


def _hs_end_type(lines: List[str], idx: int) -> int:
    last = idx
    for j in range(idx + 1, len(lines)):
        ln = lines[j]
        if not ln.strip():
            continue
        if ln[0] in " \t":
            last = j
            continue
        break
    return last + 1


_CSS_TOKEN = re.compile(r"(?<![\w-])([.#])(-?[A-Za-z_][\w-]*)")


def _css_cut_comments(ln: str) -> Tuple[str, bool]:
    """One left-to-right pass over a line: closed comments become one space, an open one cuts the line.
    Returns (text, still_inside_a_comment). Linear: every find resumes where the previous one stopped."""
    parts: List[str] = []
    pos = 0
    while True:
        a = ln.find("/*", pos)
        if a < 0:
            parts.append(ln[pos:])
            return "".join(parts), False
        parts.append(ln[pos:a])
        b = ln.find("*/", a + 2)
        if b < 0:
            return "".join(parts), True
        parts.append(" ")
        pos = b + 2


def _css_symbols(lines: List[str]) -> List[XSym]:
    out: List[XSym] = []
    depth = 0
    in_comment = False
    seen = set()
    for idx, raw in enumerate(lines):
        ln = raw
        if in_comment:
            if "*/" in ln:
                ln = ln.split("*/", 1)[1]
                in_comment = False
            else:
                continue
        if "/*" in ln:
            ln, in_comment = _css_cut_comments(ln)
        stripped = ln.strip()
        indent = len(ln) - len(ln.lstrip(" "))
        head = ln.split("{", 1)[0]
        is_sel = (
            stripped
            and not stripped.startswith(("@", "}", "//"))
            and indent <= 4 + 4 * min(depth, 1)
            and (("{" in ln) or (stripped.endswith(",") and depth == 0))
        )
        if is_sel and (depth == 0 or "{" in ln):
            for sm in _CSS_TOKEN.finditer(head):
                name = sm.group(2)
                if name in seen:
                    continue
                seen.add(name)
                out.append(XSym("selector", name, idx + 1, idx + 1, None, False, False))
        depth += ln.count("{") - ln.count("}")
        depth = max(depth, 0)
    return out


def strip_block_comments(s: str) -> str:
    """Remove every closed /* ... */ (lazily, as the old regex did); an unclosed /* stays. Linear: once a find for
    the closer fails, no later opener can close either, so the rest is copied once."""
    if "/*" not in s:
        return s
    parts: List[str] = []
    pos = 0
    while True:
        a = s.find("/*", pos)
        if a < 0:
            break
        b = s.find("*/", a + 2)
        if b < 0:
            break
        parts.append(s[pos:a])
        pos = b + 2
    parts.append(s[pos:])
    return "".join(parts)


def body_stub(lang: str, body: Optional[str]) -> Optional[str]:
    """The same contract as core.generic_body_stub for group A: why the body is a stub, else None."""
    if body is None or lang not in STUB:
        return None
    s = strip_block_comments(body)
    s = re.sub(r"(?m)//.*$", "", s)
    if lang == "php":
        s = re.sub(r"(?m)#(?!\[).*$", "", s)
    s = " ".join(s.split()).strip()
    if len(s) > STUB_MAX_CHARS:  # a stub is short; a long body is hostile or real code, and the patterns below are not run on it
        return None
    if STUB[lang].match(s):
        return "empty body" if not s else s[:40]
    return None


# ------------------------------------------------------------------ process-pool unit (picklable, pure)
def extract_unit(unit: Tuple[str, str, str]) -> str:
    """(path, lang, text) -> JSON of the symbols; pure, so it can run in a process pool."""
    _path, lang, text = unit
    return json.dumps([list(s) for s in symbols(lang, text)], separators=(",", ":"))


def from_json(blob: str) -> List[XSym]:
    return [XSym(*r) for r in json.loads(blob)]
