def resolve(tags) -> set:
    """['java', 'B', 'all'] -> set of language tags ('core' and groups expand)."""
    out: set = set()
    for t in tags:
        if t == "all":
            for g in LANG_GROUPS.values():
                out.update(g)
        elif t in LANG_GROUPS:
            out.update(LANG_GROUPS[t])
        elif t in EXTRA_LANGS or t in LANG_GROUPS["core"]:
            out.add(t)
    return out


# ------------------------------------------------------------------ helpers
class Budget:
    """A cap on the tokens brace_end may visit during one file's extraction. Without it every unclosed `{` walks to the
    end of the file, so a hostile file of n openers costs n squared. Spent = counted in tokens, not seconds, so the
    result stays deterministic; once spent, brace_end answers -1 (no pair found) and a
    declaration ends on its own line."""

    def __init__(self, tokens: int):
        self.left = tokens


_TOKEN = re.compile(r"[{}\"`'/]")
_TOKEN_HASH = re.compile(r"[{}\"`'/#]")


def brace_end(text: str, i: int, hash_comment: bool = False, budget: Optional[Budget] = None) -> int:
    """text[i] == '{'. Index after the matching '}', or -1. Skips strings and comments roughly. With a budget, -1 as
    soon as it is spent."""
    depth, n = 0, len(text)
    tok = _TOKEN_HASH if hash_comment else _TOKEN
    while i < n:
        m = tok.search(text, i)
        if m is None:
            return -1
        i = m.start()
        if budget is not None:
            budget.left -= 1
            if budget.left < 0:
                return -1
        c = text[i]
        two = text[i : i + 2]
        if (hash_comment and c == "#") or two == "//":
            j = text.find("\n", i)
            i = n if j < 0 else j
            continue
        if two == "/*":
            j = text.find("*/", i + 2)
            i = n if j < 0 else j + 2
            continue
        if c in "\"`'":
            if c == "'":
                nl = text.find("\n", i)
                if text.find("'", i + 1, n if nl < 0 else nl) < 0:
                    i += 1
                    continue
            j, k = i + 1, -2
            while True:  # the closing quote; a backslash skips the next char
                if k < j:
                    k = text.find(c, j)
                b = text.find("\\", j, n if k < 0 else k)
                if b < 0:
                    break
                j = b + 2
            if budget is not None:
                budget.left -= ((n if k < 0 else k) - i) >> 6
            i = n + 1 if k < 0 else k + 1
            continue
        if c == "{":
            depth += 1
        elif c == "}":
            depth -= 1
            if depth == 0:
                return i + 1
        i += 1
    return -1


def _annotations(lines: List[str], idx: int, lang: str, inline: str = "") -> bool:
    """True when the declaration carries a framework annotation/attribute other than the harmless set."""
    names: List[str] = []
    pat = _ANN_NAME_CS if lang == "cs" else _ANN_NAME
    if inline:
        names += [m.split(".")[-1] for m in _ANN_NAME.findall(inline)]
    j = idx - 1
    while j >= 0:
        s = lines[j].strip()
        if lang == "cs" and s.startswith("[") and s.endswith("]"):
            names += [m.split(".")[-1] for m in pat.findall(s[1:-1])]
        elif lang == "php" and s.startswith("#["):
            names += [m.split(".")[-1] for m in _ANN_NAME_CS.findall(s[2:-1])]
        elif lang in ("java", "kt", "scala", "swift", "dart") and len(s) <= MAX_SIG_LINE and _ANN_LINE.fullmatch(s):
            names += [m.split(".")[-1] for m in _ANN_NAME.findall(s)]
        elif lang == "rb" or not s:
            break
        else:
            break
        j -= 1
    return any(n not in HARMLESS_ANN for n in names)


def _public(lang: str, kind: str, name: str, mods: str, lines: List[str], idx: int) -> bool:
    m = mods.split()
    if lang in ("java", "cs"):
        return "public" in m
    if lang == "kt":
        return "private" not in m and "internal" not in m
    if lang == "swift":
        return "public" in m or "open" in m
    if lang == "scala":
        return "private" not in m and "protected" not in m
    if lang == "dart":
        return not name.startswith("_")
    if lang == "php":
        return True
    if lang == "r":
        j = idx - 1
        while j >= 0 and lines[j].lstrip().startswith("#'"):
            if re.search(r"#'\s*@export\b", lines[j]):
                return True
            j -= 1
        return False
    if lang == "lua":
        return "local" not in m
    if lang in ("rb", "ex", "hs"):
        return False
    return False


def _end_lines(lines: List[str]) -> List[int]:
    """0-based indexes of the lines that start with `end`, in order (one pass; _end_keyword bisects it)."""
    return [j for j, ln in enumerate(lines) if ln.startswith("end") and re.match(r"end\b", ln)]


def _end_keyword(lines: List[str], idx: int, ends: Optional[List[int]] = None) -> int:
    """1-based end line: the next column-0 `end` (a one-liner ends on its own line)."""
    if re.search(r"[;\s]end\s*$", lines[idx]):
        return idx + 1  # `class Foo; end`, `def x; 1 end`
    if re.match(r"^def\s.*\)\s*=\s*\S", lines[idx]):
        return idx + 1
    if ends is None:
        ends = _end_lines(lines)
    k = bisect.bisect_right(ends, idx)
    return ends[k] + 1 if k < len(ends) else idx + 1


def _hs_end(lines: List[str], idx: int, name: str, memo: Optional[Dict[str, Tuple[int, int]]] = None) -> int:
    """1-based end of a Haskell binding: the indented / same-name lines after it. The walk depends only on the line
    it stands on, so a declaration inside an earlier same-name walk shares that walk's end (`memo`: name -> (start,
    last)) instead of repeating it: n clauses cost n, not n squared."""
    if memo is not None:
        prev = memo.get(name)
        if prev is not None and prev[0] < idx <= prev[1]:
            return prev[1] + 1
    last = idx
    rx = re.compile(r"^" + re.escape(name) + r"(?![\w'])")
    for j in range(idx + 1, len(lines)):
        ln = lines[j]
        if not ln.strip():
            continue
        if ln[0] in " \t" or rx.match(ln):
            last = j
            continue
        break
    if memo is not None:
        memo[name] = (idx, last)
    return last + 1


def _c_static_fns(lines: List[str], text: str, offsets: List[int]):
    for idx, ln in enumerate(lines):
        if not ln.startswith("static ") or "(" not in ln.split("{")[0] + (
            lines[idx + 1] if idx + 1 < len(lines) else ""
        ):
            continue
        seg_end = len(text)
        window = offsets[idx] + 601  # a head longer than 600 characters is dropped below: never look further
        for ch in ("{", ";"):
            k = text.find(ch, offsets[idx], window)
            if k >= 0:
                seg_end = min(seg_end, k)
        if seg_end >= len(text) or text[seg_end] != "{" or seg_end - offsets[idx] > 600:
            continue
        head = text[offsets[idx] : seg_end]
        if "=" in head.split("(")[0] or "(" not in head:
            continue
        m = re.search(r"([A-Za-z_]\w*)\s*\($", head.split(")")[0].split("(")[0] + "(")
        if not m:
            continue
        yield idx, m.group(1), seg_end


