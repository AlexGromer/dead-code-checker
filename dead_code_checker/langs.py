def is_generated(text: str, foreign: bool = False) -> bool:
    """True when one of the first GENERATED_LINES lines (each cut to GENERATED_LINE_CAP characters) carries a
    generated-file marker. Bounded input: a long line of repeated "Code generated " cannot make the search quadratic."""
    rx = GENERATED_RE_FOREIGN if foreign else GENERATED_RE
    pos, n = 0, len(text)
    for _ in range(GENERATED_LINES):
        if pos > n:
            break
        nl = text.find("\n", pos)
        end = n if nl < 0 else nl
        if rx.search(text[pos : min(end, pos + GENERATED_LINE_CAP)]) is not None:
            return True
        if nl < 0:
            break
        pos = nl + 1
    return False
